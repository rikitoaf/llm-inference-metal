#!/usr/bin/env bash
# Environment for every dsh invocation in this workspace. Source it: `source scripts/dsh-env.sh`.
# DSH_* variables are bootstrap-only in dsh: they must be exported, a .env file cannot set them.
_dsh_env_here="${BASH_SOURCE[0]:-$0}"      # bash sets BASH_SOURCE; zsh sets $0 to the sourced file
source "$(cd "$(dirname "$_dsh_env_here")/.." && pwd)/config/stack.env"
source "$STACK_ROOT/scripts/lib/system.sh"   # ensure_model_server, defender_cpu, ...

export PATH="$NODE_BIN:$PATH"                 # dsh needs Node >= 22.19
export DSH_HOME                               # profiles, sessions, settings, credentials stay in this workspace
export DSH_AGENTS_HOME="$DSH_HOME/agents"     # keep dsh away from ~/.agents/skills
export DSH_TELEMETRY_DISABLED=1
export LLAMA_API_KEY="${LLAMA_API_KEY:-sk-local}"   # placeholder credential for the keyless local server
DSH_PATCH="$STACK_ROOT/config/dsh/qwen.cordis.patch.yml"
# The shipped patches name the default models. Another MODEL_PROFILE gets generated copies whose labels
# name the model actually served (the model id stays qwen3.8-27b-local, so sessions carry over).
if [[ "$MODEL_PROFILE" != "qwen" ]]; then
  mkdir -p "$DSH_HOME"
  DSH_PATCH="$DSH_HOME/qwen.generated.cordis.patch.yml"
  sed "s#Qwen3.8 27B GSQ-RCO IQ2_S (local)#$MODEL_LABEL (local)#" "$STACK_ROOT/config/dsh/qwen.cordis.patch.yml" > "$DSH_PATCH"
fi
# BACKEND=splash layers the Splash overrides (provider URL, JEV over /v1/systemone) on top
DSH_PATCHES=(--patch "$DSH_PATCH")
# Splash's context limit depends on its KV format (int8 ~94K, turbo-int4 ~192K, turbo ~213K on
# 24 GB) and on the memory free when it started, so the provider's contextWindow is taken from
# the running server: its limit minus the 16384-token reply budget and a 4K margin, written into a
# generated copy of the Splash patch. Without a running server the last generated value is kept (a dsh started while
# the server is down used to drop to the static 65536); with no generated copy yet, the static value applies.
splash_patch() {
  local static="$STACK_ROOT/config/dsh/splash.cordis.patch.yml"
  local limit window generated="$DSH_HOME/splash.generated.cordis.patch.yml"
  limit=$(curl -sf -m 3 "http://$LLAMA_HOST:$SPLASH_PORT/status" 2>/dev/null |
          python3 -c 'import json,sys; print(json.load(sys.stdin)["maximum_context_tokens"])' 2>/dev/null)
  if [[ "$limit" =~ ^[0-9]+$ ]]; then
    window=$(( limit - 16384 - 4096 ))
    if (( window < 4096 )); then
      echo "error: Splash's context limit $limit leaves no room for the 16384-token reply budget" >&2
      window=4096
    fi
  else                                           # no server: the last generated value, else the static one
    [[ -f "$generated" ]] && window=$(sed -n 's/.*contextWindow: \([0-9][0-9]*\).*/\1/p' "$generated")
    [[ "$window" =~ ^[0-9]+$ ]] || window=$(sed -n 's/.*contextWindow: \([0-9][0-9]*\).*/\1/p' "$static")
  fi
  # Always a generated copy, so the provider URL follows LLAMA_HOST and SPLASH_PORT too.
  local label=()                                  # the shipped labels name the default model
  [[ "$MODEL_PROFILE" != "qwen" ]] && label=(-e "s#Qwen3.8[ -]27B UD-IQ3_XXS#$MODEL_LABEL#")
  mkdir -p "$DSH_HOME"
  sed -e "s/contextWindow: [0-9][0-9]*/contextWindow: $window/" \
      -e "s/# Fallback only: scripts\/dsh-env.sh writes/# Generated by scripts\/dsh-env.sh from/" \
      -e "s#baseURL: http://127.0.0.1:8000/v1#baseURL: http://$LLAMA_HOST:$SPLASH_PORT/v1#" \
      ${label[@]+"${label[@]}"} "$static" > "$generated"
  echo "$generated"
}
[[ "$BACKEND" == "splash" ]] && DSH_PATCHES+=(--patch "$(splash_patch)")
# BACKEND=lithos: the provider follows LITHOS_PORT, and its contextWindow is the running server's --max-context
# (GET /v1/models context_window) less the 8192-token reply budget and a 4K margin.
lithos_patch() {
  local static="$STACK_ROOT/config/dsh/lithos.cordis.patch.yml"
  local limit window generated="$DSH_HOME/lithos.generated.cordis.patch.yml"
  limit=$(curl -sf -m 3 "http://$LLAMA_HOST:$LITHOS_PORT/v1/models" 2>/dev/null |
          python3 -c 'import json,sys; print(json.load(sys.stdin)["data"][0]["context_window"])' 2>/dev/null)
  if [[ "$limit" =~ ^[0-9]+$ ]]; then
    window=$(( limit - 8192 - 4096 ))
    (( window < 4096 )) && window=4096
  else
    window=$(sed -n 's/.*contextWindow: \([0-9][0-9]*\).*/\1/p' "$static")
  fi
  mkdir -p "$DSH_HOME"
  sed -e "s/contextWindow: [0-9][0-9]*/contextWindow: $window/" \
      -e "s#baseURL: http://127.0.0.1:8001/v1#baseURL: http://$LLAMA_HOST:$LITHOS_PORT/v1#" "$static" > "$generated"
  echo "$generated"
}
[[ "$BACKEND" == "lithos" ]] && DSH_PATCHES+=(--patch "$(lithos_patch)")
[[ "$JEV" != "1" ]] && DSH_PATCHES+=(--patch "$STACK_ROOT/config/dsh/nojev.cordis.patch.yml")   # JEV=1 keeps the gates
[[ "${DSH_XERJ:-0}" != "1" ]] && DSH_PATCHES+=(--patch "$STACK_ROOT/config/dsh/noxerj.cordis.patch.yml")   # xerj MCP off unless DSH_XERJ=1
[[ "${DSH_CBM:-0}" == "1" ]] && DSH_PATCHES+=(--patch "$STACK_ROOT/config/dsh/cbm.cordis.patch.yml")   # codebase-memory-mcp scout tools
[[ "${DSH_NAV_DOCTRINE:-0}" == "1" ]] && DSH_PATCHES+=(--patch "$STACK_ROOT/config/dsh/navdoctrine.cordis.patch.yml")   # grep-then-range-read rules
[[ "${DSH_READ_WINDOW:-0}" == "1" ]] && DSH_PATCHES+=(--patch "$STACK_ROOT/config/dsh/readwindow.cordis.patch.yml")   # read 400 lines per call
# DSH_REPO_MAP=/path/to/map.md: that file becomes one cached system-prompt section ("where to look" index for a
# multi-repo workspace). The file stays where it is (it may be private); only a generated patch names its path.
repo_map_patch() {
  local map_file="$1" generated="$DSH_HOME/repomap.generated.cordis.patch.yml"
  [[ -f "$map_file" && "$map_file" == *.md ]] || { echo "error: DSH_REPO_MAP must name an existing .md file" >&2; return 1; }
  mkdir -p "$DSH_HOME"
  cat > "$generated" <<EOF
# Generated by scripts/dsh-env.sh from DSH_REPO_MAP; do not edit.
- insert:
    - id: guidelines-repo-map
      name: $STACK_ROOT/plugins/dsh-plugin-guidelines/index.mjs
      config:
        rules: [$(basename "$map_file" .md)]
        ruleDirectory: $(cd "$(dirname "$map_file")" && pwd)
        sectionOrder: 10170
        isResumeNoticeEnabled: false
        areCommandsEnabled: false
EOF
  echo "$generated"
}
if [[ -n "${DSH_REPO_MAP:-}" ]]; then _repo_map_generated=$(repo_map_patch "$DSH_REPO_MAP") && DSH_PATCHES+=(--patch "$_repo_map_generated"); fi
[[ -n "${DSH_EXTRA_PATCH:-}" ]] && DSH_PATCHES+=(--patch "$DSH_EXTRA_PATCH")   # e.g. config/dsh/nojev.cordis.patch.yml

# the model server for $BACKEND answers /health
model_server_up() { curl -sf -m 3 "http://$LLAMA_HOST:$MODEL_PORT/health" >/dev/null; }

# boot a profile, creating it from a shipped template on first use
# Dynamic compaction (2026-11-13): compact when the conversation reaches the context window minus
# DSH_COMPACT_MARGIN tokens (default 10000), whatever window the running server gives (--max-context, free memory).
# The window is the server's limit minus the 20,480-token reply reserve, read from the generated provider patch.
# dsh takes a ratio, so it is computed here at launch. DSH_SHORT_CONTEXT=1 (--compact) overrides it with the fixed
# early threshold of config/dsh/shortctx.cordis.patch.yml. Prints "ratio retainTokens" (retain empty = dsh default).
compaction_settings() {
  if [[ "${DSH_SHORT_CONTEXT:-0}" == "1" ]]; then
    echo "$(sed -n 's/^ *thresholdRatio: *//p' "$STACK_ROOT/config/dsh/shortctx.cordis.patch.yml")" \
         "$(sed -n 's/^ *retainTokens: *//p' "$STACK_ROOT/config/dsh/shortctx.cordis.patch.yml")"
    return
  fi
  local window margin="${DSH_COMPACT_MARGIN:-10000}" source_patch
  for source_patch in "$DSH_HOME/$BACKEND.generated.cordis.patch.yml" "$STACK_ROOT/config/dsh/$BACKEND.cordis.patch.yml"; do
    [[ -f "$source_patch" ]] && window=$(sed -n 's/.*contextWindow: \([0-9][0-9]*\).*/\1/p' "$source_patch" | head -1)
    [[ "$window" =~ ^[0-9]+$ ]] && break
  done
  [[ "$window" =~ ^[0-9]+$ ]] || return 1
  # Floor at 50% of the window so a small window still leaves room for the retained tail.
  python3 -c "import sys; w, m = int(sys.argv[1]), int(sys.argv[2]); print(f'{max(0.5, (w - m) / w):.4f}')" "$window" "$margin"
}

# Headless profiles: a generated patch for the compaction-basic row.
compaction_patch() {
  local settings ratio retain generated="$DSH_HOME/compaction.generated.cordis.patch.yml"
  settings=$(compaction_settings) || return 1
  read -r ratio retain <<< "$settings"
  { echo "# Generated by scripts/dsh-env.sh (dynamic compaction); do not edit."
    echo "- id: compaction-basic"; echo "  config:"; echo "    thresholdRatio: $ratio"
    [[ -n "$retain" ]] && echo "    retainTokens: $retain"; } > "$generated"
  echo "$generated"
}

# Web profiles: patches cannot reach a preset's rows, so sessions get a generated preset "lean-dynamic" (the lean
# preset plus the compaction settings).
web_compact_preset_patch() {
  local root="$DSH_HOME/presets-generated" generated="$DSH_HOME/webcompact.generated.cordis.patch.yml" settings ratio retain
  settings=$(compaction_settings) || return 1
  read -r ratio retain <<< "$settings"
  mkdir -p "$root/lean-dynamic"
  sed 's/^name: .*/name: Lean, dynamic compaction (local Qwen)/' "$STACK_ROOT/config/dsh/presets/lean/preset.yml" \
    > "$root/lean-dynamic/preset.yml"
  awk -v ratio="$ratio" -v retain="$retain" '{ print }
    /dsh-compaction-basic/ { print "      config:"; print "        thresholdRatio: " ratio
                             if (retain != "") print "        retainTokens: " retain }' \
    "$STACK_ROOT/config/dsh/presets/lean/agent.cordis.yml" > "$root/lean-dynamic/agent.cordis.yml"
  printf '%s\n' "# Generated by scripts/dsh-env.sh (dynamic compaction, web); do not edit." \
    "- id: agent-presets" "  config:" "    default: lean-dynamic" "    roots:" \
    "      - path: $STACK_ROOT/config/dsh/presets" "      - path: $root" > "$generated"
  echo "$generated"
}

dsh_profile_args() {
  local profile="$1" template="$2" patches=("${DSH_PATCHES[@]}")
  # web sessions take their tools from an agent preset; this layer selects config/dsh/presets/lean
  [[ "$template" == "web" ]] && patches+=(--patch "$STACK_ROOT/config/dsh/web.cordis.patch.yml")
  local compaction_layer
  if [[ "$template" == "web" ]]; then compaction_layer=$(web_compact_preset_patch); else compaction_layer=$(compaction_patch); fi
  [[ -n "$compaction_layer" ]] && patches+=(--patch "$compaction_layer")
  if [[ -d "$DSH_HOME/profiles/$profile" ]]; then
    echo --profile "$profile" "${patches[@]}"
  else
    echo --profile "$profile" --from-default-profile "$template" "${patches[@]}"
  fi
}
